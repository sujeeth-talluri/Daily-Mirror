import sys
from pathlib import Path

from weasyprint import HTML, CSS

sys.path.insert(0, str(Path(__file__).parent))
from build_pages import render_body, format_themes, format_date, escape_html, escape_attr  # noqa: E402

ROOT = Path(__file__).parent.parent
ENTRIES_JSON = ROOT / "entries.json"
FONTS_DIR = ROOT / "fonts"
BACKUPS_DIR = ROOT / "backups"

VOLUME_SIZE = 100
AUTHOR = "Sujeeth Talluri"
ETHOS = "Truth reveals who God is. This helps me discover who I am."
ABOUT = (
    "Every morning I spend time in quiet reflection, then write one honest "
    "piece — not a lesson, not advice, just an observation about ordinary "
    "life that I hope makes you pause and ask the same question I had to "
    "ask myself: what does this reveal about me? This volume exists so "
    "these reflections outlast any single app, platform, or year."
)


