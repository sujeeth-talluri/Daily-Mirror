#!/usr/bin/env python3
"""
Generates a real, book-formatted PDF volume of the archive — cover, table
of contents with real page numbers, one chapter per entry, running headers,
page numbers — not a rendered webpage. This is the "readable without git
skills, by anyone who downloads it" durability backup: the git repo is
already the real backup, this is the human-facing one.

Triggered every VOLUME_SIZE entries (see build.yml), not on every publish:
Volume 1 = Days 1-100, Volume 2 = Days 101-200, etc. Idempotent — skips if
that volume's PDF already exists — and deliberately isolated from the daily
publish pipeline (its own CI step, its own dependency) since WeasyPrint is
too heavy to install on every push for a job that only matters once every
hundred days.

Reuses build_pages.py's render_body() so a chapter's paragraph rhythm
(pause/sequence/grouped, Mirror/Think markers) is generated by the exact
same logic as the live site — one rhythm engine, not two to keep in sync.
"""
