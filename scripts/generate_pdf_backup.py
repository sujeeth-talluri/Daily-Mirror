def render_cover(volume_num, first_day, last_day):
    return f"""
    <section class="cover">
      <div class="cover-mark" aria-hidden="true"></div>
      <div class="cover-title">The Daily Mirror</div>
      <div class="cover-rule"></div>
      <div class="cover-volume">Volume {volume_num}</div>
      <div class="cover-range">Days {first_day}&ndash;{last_day}</div>
      <div class="cover-author">{escape_html(AUTHOR)}</div>
    </section>
    """


def render_front_matter():
    return f"""
    <section class="front">
      <div class="front-title">About this book</div>
      <p>{escape_html(ABOUT)}</p>
      <p class="ethos-line">&ldquo;{escape_html(ETHOS)}&rdquo;</p>
    </section>
    """


def render_toc(entries):
    rows = []
    for e in entries:
        anchor = f"day-{e['day']}"
        rows.append(f"""
          <div class="toc-entry">
            <span class="toc-day">DAY {e['day']}</span>
            <span class="toc-entry-title">{escape_html(e['title'])}</span>
            <span class="toc-leader"></span>
            <a class="toc-page" href="#{anchor}"></a>
          </div>
        """)
    return f"""
    <section class="toc">
      <div class="toc-title">Contents</div>
      {''.join(rows)}
    </section>
    """


def render_chapter(entry):
    anchor = f"day-{entry['day']}"
    meta_parts = [f"Day {entry['day']}"]
    if entry.get("date"):
        meta_parts.append(format_date(entry["date"]))
    meta = " · ".join(meta_parts)  # a literal character, not an HTML entity —
    # escape_html() below only touches &/</>, so this survives untouched
    # instead of round-tripping through an entity and getting re-escaped.
    themes_html = format_themes(entry.get("themes")) if entry.get("themes") else ""
    image_html = ""
    if entry.get("image"):
        img_path = (ROOT / entry["image"]).resolve()
        if img_path.exists():
            image_html = f'<img class="chapter-image" src="{img_path.as_uri()}" alt="">'
    body_html = render_body(entry.get("body", ""), entry.get("closing_question", ""))
    closing_html = ""
    if entry.get("closing_question"):
        closing_html = f'<p class="closing-question">{escape_html(entry["closing_question"])}</p>'
    return f"""
    <section class="chapter" id="{anchor}">
      <div class="chapter-eyebrow">{escape_html(meta)}</div>
      <h1 class="chapter-title">{escape_html(entry['title'])}</h1>
      {f'<div class="chapter-themes">{escape_html(themes_html)}</div>' if themes_html else ''}
      {image_html}
      <div class="entry-body">{body_html}</div>
      {closing_html}
    </section>
    """


def build_volume_html(entries, volume_num, first_day, last_day):
    chapters = "".join(render_chapter(e) for e in entries)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>The Daily Mirror — Volume {volume_num}</title>
<meta name="author" content="{escape_attr(AUTHOR)}">
<style>{build_css()}</style>
</head>
<body>
{render_cover(volume_num, first_day, last_day)}
{render_front_matter()}
{render_toc(entries)}
{chapters}
</body>
</html>"""


def generate_volume(entries, volume_num):
    start = (volume_num - 1) * VOLUME_SIZE
    end = start + VOLUME_SIZE
    volume_entries = entries[start:end]
    first_day = volume_entries[0]["day"]
    last_day = volume_entries[-1]["day"]
    html = build_volume_html(volume_entries, volume_num, first_day, last_day)
    BACKUPS_DIR.mkdir(exist_ok=True)
    out_path = BACKUPS_DIR / f"the-daily-mirror-volume-{volume_num}.pdf"
    HTML(string=html, base_url=str(ROOT)).write_pdf(out_path)
    return out_path


def main():
    entries = json.loads(ENTRIES_JSON.read_text(encoding="utf-8"))
    entries = sorted(entries, key=lambda e: int(e["day"]))
    count = len(entries)
    ready_volumes = count // VOLUME_SIZE  # 100 entries -> volume 1 ready, 250 -> volumes 1-2 ready

    if ready_volumes == 0:
        print(f"{count}/{VOLUME_SIZE} entries — no volume ready yet.")
        return

    made_any = False
    for vol in range(1, ready_volumes + 1):
        out_path = BACKUPS_DIR / f"the-daily-mirror-volume-{vol}.pdf"
        if out_path.exists():
            continue
        path = generate_volume(entries, vol)
        print(f"Wrote {path}")
        made_any = True

    if not made_any:
        print(f"All {ready_volumes} ready volume(s) already exist — nothing to do.")


if __name__ == "__main__":
    main()
